  // Helper to format Tamil dates
  function formatD(dStr) {
    if (!dStr) return "";
    try {
      const d = new Date(dStr);
      if (isNaN(d.getTime())) return dStr;
      return `${d.getDate()}/${d.getMonth() + 1}/${d.getFullYear()}`;
    } catch (e) {
      return dStr;
    }
  }

  // Get Aspected Houses from a Placement House H (1..12) for a given Planet
  function getAspectedHouses(planetName, placementHouse) {
    if (!placementHouse || placementHouse < 1 || placementHouse > 12) return [];
    const aspected = new Set();
    const h = placementHouse;

    // Helper to get relative house (1-indexed)
    const rel = (offset) => ((h + offset - 1) % 12) + 1;

    // All planets aspect 7th house (offset +6)
    aspected.add(rel(6));

    if (planetName === "சனி") {
      aspected.add(rel(2));  // 3rd aspect (+2)
      aspected.add(rel(9));  // 10th aspect (+9)
    } else if (planetName === "செவ்வாய்") {
      aspected.add(rel(3));  // 4th aspect (+3)
      aspected.add(rel(7));  // 8th aspect (+7)
    } else if (planetName === "குரு" || planetName === "ராகு" || planetName === "கேது") {
      aspected.add(rel(4));  // 5th aspect (+4)
      aspected.add(rel(8));  // 9th aspect (+8)
    }

    return Array.from(aspected);
  }

  // Get Star Lord (காரக சாரிகை / Saram) of a Planet
  function getStarLordOfPlanet(planetName, context) {
    const placedPlanets = context.placedPlanets || [];
    const pObj = placedPlanets.find(p => p.planet === planetName);
    if (!pObj || !pObj.rasiId) return null;
    const deg = parseFloat(pObj.degree) || 15.0;
    const totalLon = (pObj.rasiId - 1) * 30 + deg;
    const nakIdx = Math.floor(totalLon / (360 / 27));
    return NAK_LORDS[nakIdx % 9];
  }

  // Get Direct Connections (Placement, Lordships, Aspects) for a Planet
  function getHousesForPlanetDirect(planetName, context) {
    if (!context || !planetName) return { placement: [], lordships: [], aspects: [] };
    const lagnaId = context.lagnaRasiId || (window.PGAstro && window.PGAstro.chart && window.PGAstro.chart.getLagnaRasiId()) || 1;
    const placedPlanets = context.placedPlanets || [];
    const pObj = placedPlanets.find(p => p.planet === planetName);

    let placementHouse = null;
    const placement = [];
    const lordships = [];

    // 1. Placement (அமர்வு)
    if (pObj && pObj.rasiId) {
      placementHouse = ((pObj.rasiId - lagnaId + 12) % 12) + 1;
      placement.push(placementHouse);
    }

    // 2. Lordships (ஆதிபத்தியம்)
    for (let rasiId = 1; rasiId <= 12; rasiId++) {
      if (SIGN_LORDS[rasiId] === planetName) {
        const hNo = ((rasiId - lagnaId + 12) % 12) + 1;
        lordships.push(hNo);
      }
    }

    // 3. Aspects (பார்வை: 3, 4, 5, 7, 8, 9, 10)
    const aspects = placementHouse ? getAspectedHouses(planetName, placementHouse) : [];

    return { placement, lordships, aspects };
  }

  // Get Complete Signified & Connected Houses for a Planet (Placement + Lordships + Aspects + Star Lord / Saram)
  function getHousesForPlanet(planetName, context) {
    if (!context || !planetName) return [];
    const houses = new Set();

    // 1. Direct Planet Connections (Placement, Lordships, Aspects)
    const direct = getHousesForPlanetDirect(planetName, context);
    direct.placement.forEach(h => houses.add(h));
    direct.lordships.forEach(h => houses.add(h));
    direct.aspects.forEach(h => houses.add(h));

    // 2. Star Lord (காரக சாரிகை / Saram) Connections
    const starLord = getStarLordOfPlanet(planetName, context);
    if (starLord && starLord !== planetName) {
      const starDirect = getHousesForPlanetDirect(starLord, context);
      starDirect.placement.forEach(h => houses.add(h));
      starDirect.lordships.forEach(h => houses.add(h));
      starDirect.aspects.forEach(h => houses.add(h));
    }

    return Array.from(houses).sort((a, b) => a - b);
  }

  // Get Detailed Connection Breakdown Object for a Planet
  function getPlanetConnectionDetails(planetName, context) {
    const direct = getHousesForPlanetDirect(planetName, context);
    const starLord = getStarLordOfPlanet(planetName, context);
    const starDirect = (starLord && starLord !== planetName) ? getHousesForPlanetDirect(starLord, context) : null;
    const allHouses = getHousesForPlanet(planetName, context);

    return {
      planet: planetName,
      placement: direct.placement,
      lordships: direct.lordships,
      aspects: direct.aspects,
      starLord: starLord,
      starDirect: starDirect,
      allHouses: allHouses
    };
  }

  // Evaluate if a Bhava rule matches a list of signified houses
  function evaluateRuleMatch(rule, signifiedHousesSet) {
    if (!rule || !rule.houses || rule.houses.length === 0) return { matched: false, matchScore: 0 };
    
    let hitCount = 0;
    rule.houses.forEach(h => {
      if (signifiedHousesSet.has(h)) hitCount++;
    });

    const ratio = hitCount / rule.houses.length;
    const isMatched = (ratio >= 0.66) || (rule.houses.length <= 2 && hitCount === rule.houses.length);
    return {
      matched: isMatched,
      matchScore: Math.round(ratio * 100),
      hitCount: hitCount,
      totalCount: rule.houses.length
    };
  }

  // Evaluate Timeline (Past, Present, Future) for the chart
  function evaluateTimeline(context) {
    if (!context) return null;

    const dashaRes = context.dashaResult || {};
    
    // Support various formats of bhuktis returned by astronomy / dasha engine
    let pastPeriods = dashaRes.pastBhuktis || [];
    let currentPeriod = dashaRes.currentBhukti || dashaRes.activeBhukti || null;
    let upcomingPeriods = dashaRes.upcomingBhuktis || [];

    if (dashaRes.allBhuktis && Array.isArray(dashaRes.allBhuktis)) {
      const all = dashaRes.allBhuktis;
      if (!currentPeriod && dashaRes.activeBhukti) currentPeriod = dashaRes.activeBhukti;
      
      if (currentPeriod) {
        const curIdx = all.findIndex(b => b.lord === currentPeriod.lord || (b.startDate === currentPeriod.startDate));
        if (curIdx !== -1) {
          pastPeriods = all.slice(0, curIdx);
          upcomingPeriods = all.slice(curIdx + 1);
        }
      } else if (all.length > 0) {
        currentPeriod = all[0];
        upcomingPeriods = all.slice(1);
      }
    }

    // Function to evaluate active rules for a specific Dasha-Bhukti period
    function evaluatePeriodRules(period) {
      if (!period) return { periodInfo: null, activeRules: [] };

      const mahaLord = period.mahaLord || period.lord || "";
      const bhuktiLord = period.bhuktiLord || period.lord || "";

      const mahaHouses = getHousesForPlanet(mahaLord, context);
      const bhuktiHouses = getHousesForPlanet(bhuktiLord, context);
      const combinedHouses = new Set([...mahaHouses, ...bhuktiHouses]);

      const mahaDetails = getPlanetConnectionDetails(mahaLord, context);
      const bhuktiDetails = getPlanetConnectionDetails(bhuktiLord, context);

      const activeRules = [];
      VEDIC_NADI_BHAVA_RULES.forEach(rule => {
        const evalRes = evaluateRuleMatch(rule, combinedHouses);
        if (evalRes.matched) {
          activeRules.push({
            ...rule,
            matchScore: evalRes.matchScore,
            mahaLord: mahaLord,
            bhuktiLord: bhuktiLord,
            signifiedHouses: Array.from(combinedHouses).sort((a,b)=>a-b)
          });
        }
      });

      return {
        periodInfo: period,
        mahaLord: mahaLord,
        bhuktiLord: bhuktiLord,
        mahaDetails: mahaDetails,
        bhuktiDetails: bhuktiDetails,
        combinedHouses: Array.from(combinedHouses).sort((a,b)=>a-b),
        activeRules: activeRules
      };
    }

    // Evaluate Past, Present, Future
    const pastEvaluations = pastPeriods.slice(-4).map(p => evaluatePeriodRules(p));
    const presentEvaluation = currentPeriod ? evaluatePeriodRules(currentPeriod) : null;
    const futureEvaluations = upcomingPeriods.slice(0, 5).map(p => evaluatePeriodRules(p));

    return {
      past: pastEvaluations,
      present: presentEvaluation,
      future: futureEvaluations
    };
  }

