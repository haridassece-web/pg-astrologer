  // Setup Event Listeners for UI interaction
  function setupEventListeners() {
    // Slide Navigation
    document.querySelectorAll(".bhava-slide-tab").forEach(btn => {
      btn.addEventListener("click", () => {
        const slideId = btn.dataset.slide;
        if (!slideId) return;
        currentSlideId = slideId;

        document.querySelectorAll(".bhava-slide-tab").forEach(b => {
          const isMatch = b.dataset.slide === slideId;
          b.classList.toggle("btn-gold", isMatch);
          b.classList.toggle("btn-secondary", !isMatch);
        });

        document.querySelectorAll(".bhava-slide-pane").forEach(pane => {
          const isMatch = pane.id === slideId;
          pane.classList.toggle("active", isMatch);
          pane.style.display = isMatch ? "block" : "none";
        });
      });
    });

    // Bhava Filter Buttons
    document.querySelectorAll(".bhava-filter-btn").forEach(btn => {
      btn.addEventListener("click", () => {
        activeBhavaFilter = btn.dataset.bhava || "all";
        
        document.querySelectorAll(".bhava-filter-btn").forEach(b => {
          const isMatch = b.dataset.bhava === activeBhavaFilter;
          b.classList.toggle("btn-gold", isMatch);
          b.classList.toggle("btn-secondary", !isMatch);
        });

        const grid = document.getElementById("bhavaRulesGrid");
        const searchInput = document.getElementById("bhavaRulesSearchInput");
        if (grid) {
          const context = (window.PGAstroEngine && typeof window.PGAstroEngine.getLastAnalysisObj === 'function' ? window.PGAstroEngine.getLastAnalysisObj() : null) ||
            (window.PGAstroEngine && typeof window.PGAstroEngine.evaluateCurrentChart === 'function' ? window.PGAstroEngine.evaluateCurrentChart() : null);
          grid.innerHTML = renderRulesListHtml(context, searchInput?.value.trim());
        }
      });
    });

    // Search Input
    const searchInput = document.getElementById("bhavaRulesSearchInput");
    if (searchInput) {
      searchInput.addEventListener("input", () => {
        const grid = document.getElementById("bhavaRulesGrid");
        if (grid) {
          const context = (window.PGAstroEngine && typeof window.PGAstroEngine.getLastAnalysisObj === 'function' ? window.PGAstroEngine.getLastAnalysisObj() : null) ||
            (window.PGAstroEngine && typeof window.PGAstroEngine.evaluateCurrentChart === 'function' ? window.PGAstroEngine.evaluateCurrentChart() : null);
          grid.innerHTML = renderRulesListHtml(context, searchInput.value.trim());
        }
      });
    }
  }

